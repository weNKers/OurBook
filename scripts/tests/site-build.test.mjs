test('local search indexes article titles and frontmatter metadata', () => {
  const chunksDir = path.join(outputDir, 'assets', 'chunks')
  const searchIndexName = fs.readdirSync(chunksDir).find((file) => file.startsWith('@localSearchIndexroot'))
  assert.ok(searchIndexName, 'VitePress should emit its local search index')
  const source = fs.readFileSync(path.join(chunksDir, searchIndexName), 'utf8')
  const exportStart = source.indexOf(';export')
  assert.notEqual(exportStart, -1, 'search index should expose its serialized data')
  const serialized = vm.runInNewContext(`${source.slice(0, exportStart)}; t`)
  const index = MiniSearch.loadJSON(serialized, {
    fields: ['title', 'titles', 'text'],
    storeFields: ['title', 'titles'],
    searchOptions: {
      fuzzy: 0.2,
      prefix: true,
      boost: { title: 4, text: 2, titles: 1 }
    }
  })
  const metadataQueries = ['description', 'keywords', 'contentType', 'university', 'pku']

  for (const query of metadataQueries) {
    assert.ok(
      index.search(query).some(({ id }) => id.startsWith('/universities/north/beijing/pku/1.html#')),
      `${query} metadata should be searchable`
    )
  }
  assert.ok(index.search('学校').some(({ id }) => id.startsWith('/universities/north/beijing/pku/1.html#')), 'article title should be searchable')
})
